import { z } from "zod"

/**
 * Managed tier: nhà cung cấp chạy nhiều instance cho khách trên một máy, cùng image với bản tự cài.
 * Mỗi khách = một container + một volume + một subdomain; Caddy phía trước tự cấp HTTPS.
 * File này thuần (không gọi Docker): đọc `managed/tenants.json`, sinh `tenants.yml` (compose) và `Caddyfile`.
 * CLI ở `scripts/tenant.ts`. Xem `docs/architecture/23-managed.md`.
 */

export const SLUG = /^[a-z0-9][a-z0-9-]{0,30}$/

const TenantSchema = z.object({
  /** Khách (hiện trên nhãn, không ảnh hưởng gì khác). */
  customer: z.string().optional(),
  createdAt: z.string(),
})
export const TenantsFileSchema = z.object({
  /** Subdomain của khách: `<tên>.<domain>`. `localhost` hoặc `*.localhost` → HTTP, thử trên máy dev. */
  domain: z.string().min(1),
  image: z.string().min(1).default("ghcr.io/phuchuwu/hahaness:stable"),
  tz: z.string().default("Asia/Ho_Chi_Minh"),
  /** Catalog riêng cho khách managed (tuỳ chọn). */
  catalogUrl: z.string().optional(),
  tenants: z.record(z.string().regex(SLUG), TenantSchema).default({}),
})
export type TenantsFile = z.infer<typeof TenantsFileSchema>
export type Tenant = z.infer<typeof TenantSchema>

export const service = (name: string) => `hahaness-${name}`
export const volume = (name: string) => `data-${name}`
export const host = (f: TenantsFile, name: string) => `${name}.${f.domain}`
export const local = (f: TenantsFile) => f.domain === "localhost" || f.domain.endsWith(".localhost")
export const url = (f: TenantsFile, name: string) => `${local(f) ? "http" : "https"}://${host(f, name)}`

/** Compose include: một service + một volume mỗi khách. Bản mới không tự báo vì nhà cung cấp nâng cấp. */
export function renderCompose(f: TenantsFile): string {
  const names = Object.keys(f.tenants).sort()
  const lines = ["# Generated by scripts/tenant.ts from tenants.json. Do not edit by hand.", "services:"]
  if (names.length === 0) lines.push("  {}")
  for (const n of names) {
    lines.push(
      `  ${service(n)}:`,
      `    image: ${f.image}`,
      `    restart: unless-stopped`,
      `    volumes:`,
      `      - ${volume(n)}:/data`,
      `    env_file:`,
      `      - path: env/${n}.env`,
      `        required: false`,
      `    environment:`,
      `      TZ: ${JSON.stringify(f.tz)}`,
      `      HAHANESS_UPDATE_URL: "off"`,
      ...(f.catalogUrl ? [`      HAHANESS_CATALOG_URL: ${JSON.stringify(f.catalogUrl)}`] : []),
      `    labels:`,
      `      hahaness.tenant: ${JSON.stringify(n)}`,
      ...(f.tenants[n]?.customer ? [`      hahaness.customer: ${JSON.stringify(f.tenants[n]!.customer)}`] : []),
    )
  }
  lines.push("volumes:")
  if (names.length === 0) lines.push("  {}")
  for (const n of names) lines.push(`  ${volume(n)}: {}`)
  return lines.join("\n") + "\n"
}

/** Caddy: mỗi khách một site; Caddy tự thêm X-Forwarded-Proto/For mà auth.ts cần. */
export function renderCaddy(f: TenantsFile): string {
  const names = Object.keys(f.tenants).sort()
  const lines = ["# Generated by scripts/tenant.ts from tenants.json. Do not edit by hand."]
  if (local(f)) lines.push("{", "  auto_https off", "}")
  for (const n of names) {
    lines.push("", `${local(f) ? "http://" : ""}${host(f, n)} {`, `  reverse_proxy ${service(n)}:7331`, `  encode gzip`, `}`)
  }
  if (names.length === 0) lines.push("", `# no tenants yet: run "npx tsx scripts/tenant.ts add <name>"`)
  return lines.join("\n") + "\n"
}

export function parseTenantsFile(raw: unknown): TenantsFile {
  return TenantsFileSchema.parse(raw)
}

export function addTenant(f: TenantsFile, name: string, customer?: string, now = new Date()): TenantsFile {
  if (!SLUG.test(name)) throw new Error(`tenant name must match ${SLUG} (lowercase letters, digits, dashes)`)
  if (f.tenants[name]) throw new Error(`tenant "${name}" already exists`)
  return { ...f, tenants: { ...f.tenants, [name]: { customer, createdAt: now.toISOString().slice(0, 10) } } }
}

export function removeTenant(f: TenantsFile, name: string): TenantsFile {
  if (!f.tenants[name]) throw new Error(`tenant "${name}" does not exist`)
  const { [name]: _gone, ...rest } = f.tenants
  return { ...f, tenants: rest }
}
